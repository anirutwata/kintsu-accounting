import { describe, expect, it } from 'vitest'
import { bahtText } from './bahtText'

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [100, 'หนึ่งบาทถ้วน'],
    [1100, 'สิบเอ็ดบาทถ้วน'],
    [2100, 'ยี่สิบเอ็ดบาทถ้วน'],
    [10100, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [12050, 'หนึ่งร้อยยี่สิบบาทห้าสิบสตางค์'],
    [150000, 'หนึ่งพันห้าร้อยบาทถ้วน'],
    [100000000, 'หนึ่งล้านบาทถ้วน'],
    [2100000100, 'ยี่สิบเอ็ดล้านเอ็ดบาทถ้วน'],
  ])('%i satang', (satang, text) => {
    expect(bahtText(satang)).toBe(text)
  })
})
